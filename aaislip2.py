MODEL = "gemini-3.6-flash"

SUITS = ["♠", "♥", "♦", "♣"]
RANKS = list(range(2, 15))
RANK_NAMES = {11:"J", 12:"Q", 13:"K", 14:"A"}

def card_name(card):
    return str(RANK_NAMES.get(card[0], card[0])) + card[1]

def create_deck():
    deck = [(r, s) for r in RANKS for s in SUITS]
    random.shuffle(deck)
    return deck

def evaluate_hand(cards):
    values = sorted([c[0] for c in cards], reverse=True)
    counts = Counter(values)
    suits = [c[1] for c in cards]
    flush = len(set(suits)) == 1
    unique = sorted(set(values), reverse=True)
    straight_high = 0
    if 14 in unique:
        unique.append(1)
    for i in range(len(unique)-4):
        if unique[i] - unique[i+4] == 4:
            straight_high = unique[i]
            break
    groups = sorted([(count, rank) for rank, count in counts.items()], reverse=True)

    if flush and straight_high:
        return (8, straight_high)
    if groups[0][0] == 4:
        return (7, groups[0][1], groups[1][1])
    if groups[0][0] == 3 and groups[1][0] == 2:
        return (6, groups[0][1], groups[1][1])
    if flush:
        return (5, *values)
    if straight_high:
        return (4, straight_high)
    if groups[0][0] == 3:
        return (3, groups[0][1], *sorted([r for r in values if r != groups[0][1]], reverse=True))
    if groups[0][0] == 2 and groups[1][0] == 2:
        pairs = sorted([g[1] for g in groups if g[0] == 2], reverse=True)
        kicker = max(r for r in values if r not in pairs)
        return (2, pairs[0], pairs[1], kicker)
    if groups[0][0] == 2:
        return (1, groups[0][1], *sorted([r for r in values if r != groups[0][1]], reverse=True))
    return (0, *values)

def estimate_win_probability(hole, community, opponents, simulations=1200):
    wins = 0
    ties = 0
    for _ in range(simulations):
        deck = [c for c in create_deck() if c not in hole + community]
        random.shuffle(deck)
        board = community + deck[:5-len(community)]
        index = 5-len(community)
        opponent_hands = [
            deck[index+i*2:index+(i+1)*2]
            for i in range(opponents)
        ]
        my_score = evaluate_hand(hole + board)
        opponent_scores = [evaluate_hand(hand + board) for hand in opponent_hands]
        best_opponent = max(opponent_scores)
        if my_score > best_opponent:
            wins += 1
        elif my_score == best_opponent:
            ties += 1
    return round((wins + ties*0.5)/simulations, 3)

class GamePlayingAgent:
    def __init__(self):
        self.history = defaultdict(list)
        self.opponent_profiles = defaultdict(lambda: {
            "fold": 0, "call": 0, "raise": 0
        })
        self.results = []
        self.total_wins = 0
        self.total_games = 0


    def observe(self, player, action):
        self.history[player].append(action)
        self.opponent_profiles[player][action.lower()] += 1


    def predict_opponent(self, player):
        profile = self.opponent_profiles[player]
        total = sum(profile.values())
        if total == 0:
            return "Unknown"
        return max(profile, key=profile.get)

    def choose_action(self, probability, current_bet, chips):
        if probability >= 0.70:
            return "RAISE"
        elif probability >= 0.40:
            return "CALL" if current_bet <= chips * 0.15 else "FOLD"
        elif probability >= 0.20:
            return "CALL" if current_bet <= chips * 0.05 else "FOLD"
        return "FOLD"

    def gemini_analysis(self, game_state):
        prompt = f"""
        You are a strategic poker analysis assistant.
        Analyze this simplified four-player poker game.
        Game state:
        {json.dumps(game_state, indent=2)}
        Explain:
        1. Strength of the player's hand.
        2. Opponent betting behavior.
        3. Uncertainty and possible risks.
        4. Whether the recommended action is reasonable.
        5. A short strategic recommendation.
        The mathematical win probability and recommended action are already calculated.
        Do not change them.
        """
        response = client.models.generate_content(
            model=MODEL,
            contents=prompt
        )
        return response.text

    def update_result(self, won):
        self.total_games += 1
        if won:
            self.total_wins += 1
        self.results.append("WIN" if won else "LOSS")

    def report(self):
        print("\n========== LONG-TERM PERFORMANCE REPORT ==========")
        print("Total Games:", self.total_games)
        print("Total Wins:", self.total_wins)
        print("Total Losses:", self.total_games-self.total_wins)
        print("Win Rate:", round(self.total_wins/max(1,self.total_games)*100,2), "%")
        print("\nOpponent Action Histories:")
        for player, actions in self.history.items():
            print(player, actions)
        print("\nOpponent Behavior Profiles:")
        for player in self.opponent_profiles:
            print(player, dict(self.opponent_profiles[player]))
        print("\nGame Results:", self.results)

def play_game(agent, round_number):
    deck = create_deck()
    player_hand = deck[:2]
    community = deck[2:7]
    opponents = ["Player 2", "Player 3", "Player 4"]

    print("\n" + "="*55)
    print("GAME ROUND", round_number)
    print("="*55)

    print("Your Private Cards:", [card_name(c) for c in player_hand])
    print("Community Cards:", [card_name(c) for c in community[:3]])

    betting_actions = {}
    for player in opponents:
        action = random.choices(
            ["FOLD", "CALL", "RAISE"],
            weights=[0.25, 0.55, 0.20],
            k=1
        )[0]
        betting_actions[player] = action
        agent.observe(player, action)

    print("\nOpponent Actions:")
    for player, action in betting_actions.items():
        print(player, ":", action, "| Predicted behavior:", agent.predict_opponent(player))

    probability = estimate_win_probability(
        player_hand,
        community[:3],
        len(opponents)
    )

    current_bet = random.choice([10, 20, 50, 100])
    chips = 1000
    action = agent.choose_action(probability, current_bet, chips)

    print("\nEstimated Win Probability:", probability*100, "%")
    print("Current Bet:", current_bet)
    print("Available Chips:", chips)
    print("AI Recommended Action:", action)

    game_state = {
        "round": round_number,
        "private_cards": [card_name(c) for c in player_hand],
        "community_cards": [card_name(c) for c in community[:3]],
        "opponent_actions": betting_actions,
        "opponent_predictions": {
            p: agent.predict_opponent(p) for p in opponents
        },
        "win_probability": probability,
        "recommended_action": action,
        "current_bet": current_bet
    }

    print("\n========== GEMINI STRATEGIC ANALYSIS ==========")
    try:
        print(agent.gemini_analysis(game_state))
    except Exception as e:
        print("Gemini analysis unavailable:", str(e))

    print("\n========== SHOWDOWN ==========")
    print("Final Community Cards:", [card_name(c) for c in community])

    my_score = evaluate_hand(player_hand + community)
    opponent_hands = [deck[7+i*2:9+i*2] for i in range(3)]
    opponent_scores = [evaluate_hand(h + community) for h in opponent_hands]

    best_score = max([my_score] + opponent_scores)
    won = my_score == best_score

    if won:
        print("Result: YOU WIN")
    else:
        print("Result: YOU LOSE")

    print("Your Hand Score:", my_score)
    print("Best Opponent Score:", max(opponent_scores))

    agent.update_result(won)

