import requests
import json
from google import genai
from getpass import getpass

API_KEY = getpass("Enter your Gemini API Key: ")
client = genai.Client(api_key=API_KEY)

MODEL = "gemini-3.5-flash-lite"

session = requests.Session()
session.headers.update({
    "User-Agent": "WikipediaSearchAgent/1.0 (educational project)"
})

def gemini(prompt):
    response = client.models.generate_content(
        model=MODEL,
        contents=prompt
    )
    return response.text

def wikipedia_search(query):
    url = "https://en.wikipedia.org/w/api.php"

    params = {
        "action": "query",
        "list": "search",
        "srsearch": query,
        "srlimit": 5,
        "format": "json"
    }

    response = session.get(url, params=params, timeout=20)
    response.raise_for_status()

    results = response.json()["query"]["search"]

    return [
        {
            "title": item["title"],
            "snippet": item["snippet"]
        }
        for item in results
    ]

def get_article(title):
    url = "https://en.wikipedia.org/w/api.php"

    params = {
        "action": "query",
        "prop": "extracts|info",
        "explaintext": 1,
        "exintro": 0,
        "exchars": 12000,
        "inprop": "url",
        "titles": title,
        "format": "json"
    }

    response = session.get(url, params=params, timeout=20)
    response.raise_for_status()

    pages = response.json()["query"]["pages"]
    page = next(iter(pages.values()))

    return {
        "title": page.get("title", title),
        "content": page.get("extract", ""),
        "url": page.get("fullurl", "")
    }

class WikipediaSearchAgent:

    def __init__(self):
        self.history = []

    def run(self, question):

        print("\nAgent: Understanding your query...")

        search_prompt = f"""
        You are a Wikipedia search agent.
        Identify 2 to 3 effective Wikipedia search queries
        for the following question.

        Question: {question}

        Return only valid JSON:
        {{
            "queries": ["query 1", "query 2"]
        }}
        """

        try:
            response = gemini(search_prompt)
            cleaned = response.replace("```json", "").replace("```", "").strip()
            queries = json.loads(cleaned)["queries"]
        except Exception:
            queries = [question]

        print("Agent: Searching Wikipedia...")

        search_results = {}

        for query in queries[:3]:
            try:
                results = wikipedia_search(query)

                for item in results:
                    search_results[item["title"]] = item

            except Exception as e:
                print("Search warning:", e)

        if not search_results:
            print("No Wikipedia articles found.")
            return

        selected_titles = list(search_results.keys())[:5]

        print("Agent: Retrieving articles...")

        articles = []

        for title in selected_titles:
            try:
                article = get_article(title)

                if article["content"].strip():
                    articles.append(article)

            except Exception as e:
                print("Article retrieval warning:", e)

        if not articles:
            print("Unable to retrieve article content.")
            return

        context = ""

        for article in articles:
            context += (
                "\n\nARTICLE: " + article["title"] +
                "\nURL: " + article["url"] +
                "\nCONTENT:\n" + article["content"][:10000]
            )

        print("Agent: Generating answer...\n")

        final_prompt = f"""
        You are an intelligent Wikipedia Search Agent.

        Answer the user's question using ONLY the supplied
        Wikipedia article content.

        User Question:
        {question}

        Retrieved Wikipedia Articles:
        {context}

        Instructions:
        1. Provide a clear and accurate answer.
        2. Organize the answer using headings and bullet points.
        3. Include important facts and explanations.
        4. Do not invent facts that are absent from the articles.
        5. If information is insufficient, clearly mention it.
        6. Mention which articles support the answer.
        7. Do not invent references or URLs.
        """

        answer = gemini(final_prompt)

        print("=" * 65)
        print("WIKIPEDIA SEARCH AGENT - FINAL ANSWER")
        print("=" * 65)
        print(answer)

        print("\nSOURCES:")
        for i, article in enumerate(articles, 1):
            print(f"{i}. {article['title']}")
            print(article["url"])

        self.history.append({
            "question": question,
            "articles": [a["title"] for a in articles],
            "answer": answer
        })

        print("\nAgent execution completed successfully.")

agent = WikipediaSearchAgent()

question = input("Enter your question: ")
agent.run(question)